"""MCP tool: draft_memo — insert a memo-type row into tax_review_queue.

Used by the 1120 Preparer specialist to record observations, notes, or
questions for CPA review that do not reference a specific form line.

Examples of memo use:
  - "The entity has $2,400 in Banking · Interest income. Verify whether this
    is taxable interest (line 5) or interest on U.S. obligations (line 4)."
  - "Owner distributions totaling $48,000 were recorded in Q3. Confirm
    Schedule L retained-earnings rollforward."
  - "Three large inter-entity transfers ($15,000+) need CPA review for
    related-party characterization before line 26 placement."

Write tool — requires accountant role (same floor as other queue-write operations).
"""
from __future__ import annotations

from typing import Any
from uuid import UUID

from sqlalchemy import text

from app.db import SessionLocal
from app.mcp_auth import authorize_workspace, current_auth
from app.workspace_session import workspace_session

_VALID_CONFIDENCE = frozenset({"low", "medium", "high"})


async def draft_memo(
    workspace_id: UUID,
    entity_id: UUID,
    tax_year: int,
    topic: str,
    content: str,
    citations: list[dict[str, str]] | None = None,
    confidence: str = "medium",
) -> dict[str, Any]:
    """Insert a memo-type item into the tax review queue.

    Creates a ``memo`` row in ``tax_review_queue`` capturing a specialist
    observation for CPA review. The memo is not associated with a specific
    form line; use ``flag_for_cpa_review`` for form-line-specific flags.

    Args:
        workspace_id: Workspace UUID.
        entity_id: Entity UUID.
        tax_year: Tax year (e.g. 2023).
        topic: Short title for the memo (e.g. "Banking interest classification").
        content: Full memo text (the specialist's observation or question).
        citations: Optional list of citations, each ``{"type": "section"|
            "journal_entry"|"form_line", "value": "..."}`` — e.g.
            ``[{"type": "section", "value": "§163(j)"}]``.
        confidence: Specialist's confidence level: 'low' | 'medium' | 'high'.
            Default 'medium'.

    Returns:
        {"ok": True, "item_id": "<uuid>", "item_type": "memo", "_draft_notice": "..."}

    DRAFT — for CPA review only.

    Role floor: accountant.
    """
    ctx = await authorize_workspace(workspace_id, entity_id, min_role="accountant")

    confidence = (confidence or "medium").strip().lower()
    if confidence not in _VALID_CONFIDENCE:
        raise ValueError(
            f"confidence must be 'low', 'medium', or 'high'; got {confidence!r}"
        )

    # Resolve the submitter id: prefer agent_id (for the specialist agent),
    # fall back to uc_uid (for a human calling via the MCP surface directly).
    auth = current_auth()
    submitter_id = (auth.agent_id or auth.uc_uid) if auth else "unknown"
    submitter_kind = "agent" if (auth and auth.agent_id) else "human"

    content_payload: dict[str, Any] = {
        "topic": str(topic).strip(),
        "text": str(content).strip(),
    }
    citations_val = citations or []

    import json

    async with workspace_session(SessionLocal, workspace_id) as session:
        row = (
            await session.execute(
                text(
                    """
                    INSERT INTO tax_review_queue (
                        workspace_id, entity_id, tax_year,
                        item_type, form_reference,
                        content, confidence, citations,
                        status, submitter_kind, submitter_id
                    ) VALUES (
                        :workspace_id, :entity_id, :tax_year,
                        'memo', NULL,
                        CAST(:content AS jsonb), :confidence,
                        CAST(:citations AS jsonb),
                        'pending', :submitter_kind, :submitter_id
                    )
                    RETURNING CAST(id AS text) AS id
                    """
                ),
                {
                    "workspace_id": str(workspace_id),
                    "entity_id": str(entity_id),
                    "tax_year": tax_year,
                    "content": json.dumps(content_payload),
                    "confidence": confidence,
                    "citations": json.dumps(citations_val),
                    "submitter_kind": submitter_kind,
                    "submitter_id": submitter_id,
                },
            )
        ).mappings().first()

    return {
        "ok": True,
        "item_id": row["id"],
        "item_type": "memo",
        "tax_year": tax_year,
        "entity_id": str(entity_id),
        "_draft_notice": (
            "DRAFT — for CPA review only. "
            "This memo was generated by the 1120 Preparer specialist and is "
            "queued for CPA review. No tax position has been established."
        ),
    }
