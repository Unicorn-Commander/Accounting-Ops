function ChallengeDialog({
  workspaceId,
  row,
  onClose,
  onSubmitted
}: {
  workspaceId: string;
  row: AIActivityRow;
  onClose: () => void;
  onSubmitted: (memoId: string) => void;
}) {
  const [reason, setReason] = useState("");
  const [submitting, setSubmitting] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const submit = async () => {
    const r = reason.trim();
    if (!r) {
      setError("Add a reason — 1-3 sentences is fine.");
      return;
    }
    setSubmitting(true);
    setError(null);
    try {
      const res = await fetch(
        `/api/workspaces/${workspaceId}/ai-activity/${encodeURIComponent(row.id)}/challenge`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ reason: r })
        }
      );
      if (!res.ok) {
        const j = (await res.json().catch(() => ({}))) as Record<string, unknown>;
        throw new Error(
          (j.detail as string) ?? `Challenge failed (HTTP ${res.status})`
        );
      }
      const j = (await res.json()) as { memo_id: string };
      onSubmitted(j.memo_id);
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <div
      className="fixed inset-0 z-50 flex items-center justify-center bg-canvas/70 px-4 backdrop-blur-sm"
      onClick={onClose}
    >
      <div
        className="w-full max-w-lg rounded-xl border border-strong bg-surface p-5 shadow-card"
        onClick={(e) => e.stopPropagation()}
      >
        <header className="mb-3 flex items-start gap-3">
          <Flag size={18} className="mt-0.5 text-pending" />
          <div className="min-w-0 flex-1">
            <h3 className="text-base font-semibold">Challenge this AI output</h3>
            <p className="mt-1 text-xs text-ink-tertiary">
              Files a memo to the CPA queue linking back to the original
              action. The AI output itself stays where it is; this just flags
              your disagreement for review.
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            aria-label="Close"
            className="text-ink-tertiary hover:text-ink-primary"
          >
            <XCircle size={16} />
          </button>
        </header>

        <div className="mb-3 rounded-md border border-subtle bg-canvas/40 px-3 py-2 text-[11px] text-ink-secondary">
          <div className="flex items-center gap-1.5">
            <AIGeneratedBadge agentId={row.agent_id} />
            <span className="font-mono text-ink-tertiary">
              {row.action_label}
            </span>
            <span className="text-ink-tertiary">·</span>
            <span>{relativeTime(row.created_at)}</span>
          </div>
          {row.target.tax_year ? (
            <p className="mt-1 font-mono text-[10px] text-ink-tertiary">
              TY {String(row.target.tax_year)} · {row.entity_display_name ?? "—"}
            </p>
          ) : null}
        </div>

        <label className="mb-1 block text-[11px] font-medium uppercase tracking-wider text-ink-tertiary">
          Reason
        </label>
        <textarea
          value={reason}
          onChange={(e) => setReason(e.target.value)}
          placeholder="What did the AI get wrong? 1–3 sentences."
          rows={4}
          className="w-full rounded-md border border-default bg-canvas/60 px-3 py-2 text-sm text-ink-primary placeholder:text-ink-tertiary focus:border-brand-500/60 focus:outline-none"
          disabled={submitting}
        />

        {error ? (
          <p className="mt-2 flex items-center gap-1.5 text-xs text-debit">
            <AlertCircle size={12} />
            {error}
          </p>
        ) : null}

        <div className="mt-4 flex items-center justify-end gap-2">
          <button
            type="button"
            onClick={onClose}
            disabled={submitting}
            className="rounded-md border border-strong bg-white/[0.03] px-3 py-1.5 text-xs font-medium text-ink-secondary transition hover:bg-white/[0.06] hover:text-ink-primary"
          >
            Cancel
          </button>
          <button
            type="button"
            onClick={submit}
            disabled={submitting || !reason.trim()}
            className={cn(
              "inline-flex items-center gap-1.5 rounded-md bg-pending px-3 py-1.5 text-xs font-medium text-canvas shadow-brand-glow transition hover:opacity-90",
              (submitting || !reason.trim()) && "opacity-60"
            )}
          >
            <Flag size={12} />
            {submitting ? "Filing…" : "File challenge"}
          </button>
        </div>
      </div>
    </div>
  );
}

