function TimelineRow({
  workspaceId,
  row,
  onChanged
}: {
  workspaceId: string;
  row: AIActivityRow;
  onChanged: () => void;
}) {
  const router = useRouter();
  const [open, setOpen] = useState(false);
  const [pending, startTransition] = useTransition();
  const [undoing, setUndoing] = useState(false);
  const [challenge, setChallenge] = useState(false);
  const [localStatus, setLocalStatus] = useState<{
    undone: boolean;
    challenged: boolean;
    error: string | null;
    memoId?: string;
  }>({
    undone: !!row.undone_at,
    challenged: !!row.challenged_at,
    error: null,
    memoId: row.challenge_memo_id ?? undefined
  });

  const doUndo = async () => {
    setUndoing(true);
    setLocalStatus((s) => ({ ...s, error: null }));
    try {
      const res = await fetch(
        `/api/workspaces/${workspaceId}/ai-activity/${encodeURIComponent(row.id)}/undo`,
        {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ note: "Undone via /open-items timeline" })
        }
      );
      if (!res.ok) {
        const j = (await res.json().catch(() => ({}))) as Record<string, unknown>;
        const detail = j.detail as
          | { code?: string; message?: string }
          | string
          | undefined;
        const msg =
          typeof detail === "string"
            ? detail
            : detail?.message ?? `Undo failed (HTTP ${res.status})`;
        throw new Error(msg);
      }
      setLocalStatus((s) => ({ ...s, undone: true, error: null }));
      startTransition(() => {
        router.refresh();
        onChanged();
      });
    } catch (e) {
      setLocalStatus((s) => ({
        ...s,
        error: e instanceof Error ? e.message : String(e)
      }));
    } finally {
      setUndoing(false);
    }
  };

  const onChallengeSubmitted = (memoId: string) => {
    setChallenge(false);
    setLocalStatus((s) => ({
      ...s,
      challenged: true,
      memoId,
      error: null
    }));
    startTransition(() => {
      router.refresh();
      onChanged();
    });
  };

  const oStyle = outcomeStyle(row.outcome);

  return (
    <li
      className={cn(
        "border-l-2 px-4 py-3 transition hover:bg-white/[0.02] md:px-5",
        localStatus.undone
          ? "border-l-ink-disabled/40 opacity-70"
          : localStatus.challenged
            ? "border-l-pending/60"
            : "border-l-agent-500/40"
      )}
    >
      <div className="flex items-start gap-3">
        <button
          type="button"
          aria-label={open ? "Collapse" : "Expand"}
          onClick={() => setOpen((o) => !o)}
          className="mt-0.5 shrink-0 text-ink-tertiary hover:text-ink-primary"
        >
          {open ? <ChevronDown size={14} /> : <ChevronRight size={14} />}
        </button>
        <div className="min-w-0 flex-1">
          <div className="flex flex-wrap items-center gap-x-2 gap-y-1">
            <span className="font-mono text-[11px] text-ink-tertiary">
              {timeOfDay(row.created_at)}
            </span>
            <AIGeneratedBadge
              agentId={row.agent_id}
              hover={`${agentDisplayName(row.agent_id)} — ${relativeTime(row.created_at)}`}
            />
            <span className="text-xs font-semibold text-agent-500">
              {agentDisplayName(row.agent_id)}
            </span>
            <span className="text-[10px] text-ink-tertiary">·</span>
            <span className="text-sm text-ink-primary">{row.action_label}</span>
            {row.target.tax_year ? (
              <span className="rounded-full bg-white/[0.05] px-1.5 py-0.5 font-mono text-[10px] text-ink-tertiary">
                TY {String(row.target.tax_year)}
              </span>
            ) : null}
            {row.entity_display_name ? (
              <span className="text-[10px] text-ink-tertiary">
                · {row.entity_display_name}
              </span>
            ) : null}
            <OutcomeChip outcome={row.outcome} />
            {row.auto_applied ? (
              <span
                className="inline-flex items-center gap-1 rounded-md bg-credit/10 px-1.5 py-0.5 text-[10px] font-medium text-credit"
                title="No human decision was needed for this action"
              >
                Auto-applied
              </span>
            ) : (
              <span
                className="inline-flex items-center gap-1 rounded-md bg-brand-500/10 px-1.5 py-0.5 text-[10px] font-medium text-brand-300"
                title="A human reviewed before this action took effect"
              >
                Human-decided
              </span>
            )}
            {localStatus.undone ? (
              <span className="inline-flex items-center gap-1 rounded-md bg-white/[0.05] px-1.5 py-0.5 text-[10px] font-medium text-ink-tertiary">
                <Undo2 size={10} /> Undone
              </span>
            ) : null}
            {localStatus.challenged ? (
              <span className="inline-flex items-center gap-1 rounded-md bg-pending/10 px-1.5 py-0.5 text-[10px] font-medium text-pending">
                <Flag size={10} /> Challenged
              </span>
            ) : null}
          </div>

          {row.reasoning_trace ? (
            <p
              className={cn(
                "mt-1 text-[11px] leading-relaxed text-ink-secondary",
                !open && "line-clamp-1"
              )}
              title={!open ? row.reasoning_trace : undefined}
            >
              <span className="text-ink-tertiary">Why: </span>
              {row.reasoning_trace}
            </p>
          ) : null}

          {/* artifact link */}
          {row.artifact ? (
            <div className="mt-1.5">
              <span className="text-[11px] text-ink-tertiary">
                Artifact:{" "}
                <span className="text-ink-secondary">
                  {row.artifact.label}
                </span>
                {row.artifact.kind === "tax_review_queue_item" ? (
                  <Link
                    href={`/taxes/${row.target.tax_year ?? ""}`}
                    className="ml-1 text-brand-400 hover:underline"
                  >
                    open
                  </Link>
                ) : null}
              </span>
            </div>
          ) : null}

          {/* expanded body */}
          {open ? (
            <div className="mt-3 space-y-1 rounded-md border border-subtle bg-canvas/40 px-3 py-2.5">
              <div className="grid grid-cols-1 gap-x-4 gap-y-1 text-[11px] sm:grid-cols-2">
                <div>
                  <span className="text-ink-tertiary">Tool: </span>
                  <code className="text-ink-secondary">{row.tool_name}</code>
                </div>
                <div>
                  <span className="text-ink-tertiary">Outcome: </span>
                  <span className="text-ink-secondary">{row.outcome}</span>
                </div>
                {row.latency_ms !== null ? (
                  <div>
                    <span className="text-ink-tertiary">Latency: </span>
                    <span className="font-mono text-ink-secondary">
                      {row.latency_ms} ms
                    </span>
                  </div>
                ) : null}
                <div>
                  <span className="text-ink-tertiary">Reversible: </span>
                  <span
                    className={cn(
                      row.reversible ? "text-credit" : "text-ink-secondary"
                    )}
                  >
                    {row.reversible
                      ? "yes"
                      : row.reverse_kind
                        ? "window expired"
                        : "no — challenge only"}
                  </span>
                </div>
                {row.undone_at ? (
                  <div className="col-span-full text-ink-tertiary">
                    Undone {relativeTime(row.undone_at)} by{" "}
                    <span className="text-ink-secondary">{row.undone_by}</span>
                  </div>
                ) : null}
                {row.challenged_at ? (
                  <div className="col-span-full text-pending">
                    Challenged {relativeTime(row.challenged_at)} by{" "}
                    <span className="text-ink-secondary">
                      {row.challenged_by}
                    </span>
                  </div>
                ) : null}
              </div>
              <JsonBlock label="Request" data={row.request_payload} />
              <JsonBlock label="Response (before → after diff)" data={row.response_payload} />
            </div>
          ) : null}

          {/* error surface */}
          {localStatus.error ? (
            <div className="mt-2 flex items-start gap-1.5 rounded-md border border-debit/40 bg-debit/[0.05] px-2 py-1.5 text-[11px] text-debit">
              <AlertCircle size={11} className="mt-0.5 shrink-0" />
              <span className="min-w-0">{localStatus.error}</span>
            </div>
          ) : null}

          {/* actions */}
          <div className="mt-2.5 flex flex-wrap items-center gap-2">
            {row.reversible && !localStatus.undone ? (
              <button
                type="button"
                onClick={doUndo}
                disabled={undoing || pending}
                className={cn(
                  "inline-flex items-center gap-1 rounded-md border border-strong bg-white/[0.04] px-2.5 py-1 text-[11px] font-medium text-ink-secondary transition hover:bg-white/[0.08] hover:text-ink-primary",
                  (undoing || pending) && "opacity-60"
                )}
                title={
                  row.reverse_window_hours >= 24 * 365
                    ? "Reversible at any time"
                    : `Reversible within ${row.reverse_window_hours}h of the action`
                }
              >
                <Undo2 size={11} />
                {undoing ? "Undoing…" : "Undo"}
              </button>
            ) : null}
            {!localStatus.challenged ? (
              <button
                type="button"
                onClick={() => setChallenge(true)}
                className="inline-flex items-center gap-1 rounded-md border border-strong bg-white/[0.04] px-2.5 py-1 text-[11px] font-medium text-ink-secondary transition hover:bg-pending/10 hover:text-pending"
              >
                <Flag size={11} />
                Challenge this
              </button>
            ) : (
              <span className="text-[11px] text-pending">
                Challenge filed
                {localStatus.memoId ? (
                  <>
                    {" — "}
                    <Link
                      href={`/taxes/${row.target.tax_year ?? ""}`}
                      className="underline-offset-2 hover:underline"
                    >
                      view memo
                    </Link>
                  </>
                ) : null}
              </span>
            )}
          </div>
        </div>
      </div>

      {challenge ? (
        <ChallengeDialog
          workspaceId={workspaceId}
          row={row}
          onClose={() => setChallenge(false)}
          onSubmitted={onChallengeSubmitted}
        />
      ) : null}
    </li>
  );
}

