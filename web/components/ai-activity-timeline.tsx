export function AIActivityTimeline({
  workspaceId,
  initial,
  entityId,
  emptyMsg = "No AI activity yet for the selected filters."
}: {
  workspaceId: string;
  initial: AIActivityResponse | null;
  entityId?: string;
  emptyMsg?: string;
}) {
  const [data, setData] = useState<AIActivityResponse | null>(initial);
  const [filters, setFilters] = useState<FilterState>({
    agent: "",
    action: "",
    since: "",
    live: false
  });
  const [busy, setBusy] = useState(false);
  const lastTickRef = useRef<number>(Date.now());
  const liveRef = useRef<boolean>(false);
  liveRef.current = filters.live;

  // Aggregate the set of agent ids the user has seen — feeds the filter dropdown.
  const agentOptions = useMemo(() => {
    const s = new Set<string>();
    data?.rows.forEach((r) => s.add(r.agent_id));
    return Array.from(s).sort();
  }, [data]);

  // ---- Refetch on filter change.
  useEffect(() => {
    const fetcher = async () => {
      setBusy(true);
      try {
        const params = new URLSearchParams();
        if (entityId) params.set("entity_id", entityId);
        if (filters.agent) params.set("agent", filters.agent);
        if (filters.action) params.set("action", filters.action);
        if (filters.since) {
          // Treat as start-of-day UTC
          params.set("since", new Date(filters.since).toISOString());
        }
        params.set("limit", "100");
        const res = await fetch(
          `/api/workspaces/${workspaceId}/ai-activity?${params.toString()}`,
          { cache: "no-store" }
        );
        if (res.ok) {
          setData((await res.json()) as AIActivityResponse);
          lastTickRef.current = Date.now();
        }
      } finally {
        setBusy(false);
      }
    };
    // Skip the initial fetch — the server component provided `initial`.
    if (filters.agent || filters.action || filters.since) {
      fetcher();
    }
  }, [workspaceId, entityId, filters.agent, filters.action, filters.since]);

  // ---- Live updates via polling /ai-activity (no SSE complexity from the
  //      client side; the FastAPI SSE stream exists for power users / external
  //      clients).
  useEffect(() => {
    if (!filters.live) return;
    const interval = setInterval(async () => {
      if (!liveRef.current) return;
      try {
        const params = new URLSearchParams();
        if (entityId) params.set("entity_id", entityId);
        if (filters.agent) params.set("agent", filters.agent);
        if (filters.action) params.set("action", filters.action);
        params.set("limit", "100");
        const res = await fetch(
          `/api/workspaces/${workspaceId}/ai-activity?${params.toString()}`,
          { cache: "no-store" }
        );
        if (res.ok) {
          setData((await res.json()) as AIActivityResponse);
          lastTickRef.current = Date.now();
        }
      } catch {
        // best-effort
      }
    }, 5000);
    return () => clearInterval(interval);
  }, [filters.live, workspaceId, entityId, filters.agent, filters.action]);

  const rows = data?.rows ?? [];

  // Group by agent for the "group by agent" view — but only when the user
  // hasn't filtered down to a single agent already.
  const grouped = useMemo(() => {
    const out: { agent: string; rows: AIActivityRow[] }[] = [];
    const seen: Record<string, number> = {};
    for (const r of rows) {
      const idx = seen[r.agent_id];
      if (idx !== undefined) {
        out[idx].rows.push(r);
      } else {
        seen[r.agent_id] = out.length;
        out.push({ agent: r.agent_id, rows: [r] });
      }
    }
    return out;
  }, [rows]);

  // Trigger refetch hook the children call after undo/challenge — uses the
  // same fetcher as the live tick.
  const refresh = async () => {
    try {
      const params = new URLSearchParams();
      if (entityId) params.set("entity_id", entityId);
      if (filters.agent) params.set("agent", filters.agent);
      if (filters.action) params.set("action", filters.action);
      if (filters.since) {
        params.set("since", new Date(filters.since).toISOString());
      }
      params.set("limit", "100");
      const res = await fetch(
        `/api/workspaces/${workspaceId}/ai-activity?${params.toString()}`,
        { cache: "no-store" }
      );
      if (res.ok) {
        setData((await res.json()) as AIActivityResponse);
      }
    } catch {
      // best-effort
    }
  };

  return (
    <Card padded={false} className="overflow-hidden">
      <FilterBar
        filters={filters}
        onChange={setFilters}
        agents={agentOptions}
      />
      {filters.live ? (
        <div className="flex items-center gap-2 border-b border-subtle bg-agent-500/[0.05] px-3 py-1.5 text-[10px] text-agent-500">
          <Radio size={11} className="animate-pulse-soft" />
          Live — polling every 5s
          <span className="ml-auto text-ink-tertiary">
            {busy ? "fetching…" : `last update ${relativeTime(new Date(lastTickRef.current).toISOString())}`}
          </span>
        </div>
      ) : null}
      {rows.length === 0 ? (
        <div className="px-5 py-6">
          <p className="text-sm text-ink-tertiary">{emptyMsg}</p>
        </div>
      ) : (
        <div className="divide-y divide-subtle/60">
          {grouped.map((g) => (
            <div key={g.agent}>
              <div className="bg-canvas/30 px-4 py-2 text-[10px] font-medium uppercase tracking-wider text-ink-tertiary md:px-5">
                <span className="text-agent-500">
                  {agentDisplayName(g.agent)}
                </span>
                <span className="ml-2 text-ink-tertiary">
                  · {g.rows.length} action{g.rows.length === 1 ? "" : "s"}
                </span>
              </div>
              <ul className="divide-y divide-subtle/60">
                {g.rows.map((r) => (
                  <TimelineRow
                    key={r.id}
                    workspaceId={workspaceId}
                    row={r}
                    onChanged={refresh}
                  />
                ))}
              </ul>
            </div>
          ))}
        </div>
      )}
      <div className="flex items-center justify-between border-t border-subtle px-4 py-2 text-[10px] text-ink-tertiary md:px-5">
        <span>
          {rows.length} action{rows.length === 1 ? "" : "s"} shown
          {data ? ` · as of ${new Date(data.as_of).toLocaleString()}` : ""}
        </span>
        <span>
          All actions logged to <code>decision_audit</code> · append-only ·
          tamper-evident
        </span>
      </div>
    </Card>
  );
}
