function OutcomeChip({ outcome }: { outcome: string }) {
  const s = outcomeStyle(outcome);
  return (
    <span
      className={cn(
        "inline-flex items-center gap-1 rounded-md px-1.5 py-0.5 text-[10px] font-medium uppercase tracking-wider",
        s.bg
      )}
    >
      {s.icon}
      {outcome.replace(/_/g, " ")}
    </span>
  );
}

function JsonBlock({
  label,
  data
}: {
  label: string;
  data: unknown;
}) {
  if (data === null || data === undefined) return null;
  let preview: string;
  try {
    preview = JSON.stringify(data, null, 2);
  } catch {
    preview = String(data);
  }
  if (!preview || preview === "{}" || preview === "null") return null;
  return (
    <details className="mt-2">
      <summary className="cursor-pointer text-[10px] font-medium uppercase tracking-wider text-ink-tertiary hover:text-ink-secondary">
        {label}
      </summary>
      <pre className="mt-1 max-h-60 overflow-auto rounded-md bg-canvas/60 p-2 text-[11px] leading-relaxed text-ink-secondary">
        {preview}
      </pre>
    </details>
  );
}

