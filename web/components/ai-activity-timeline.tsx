function relativeTime(iso: string): string {
  const t = new Date(iso).getTime();
  const now = Date.now();
  const delta = Math.max(0, Math.floor((now - t) / 1000));
  if (delta < 60) return `${delta}s ago`;
  if (delta < 3600) return `${Math.floor(delta / 60)}m ago`;
  if (delta < 86400) return `${Math.floor(delta / 3600)}h ago`;
  return new Date(iso).toLocaleDateString();
}

function timeOfDay(iso: string): string {
  return new Date(iso).toLocaleTimeString(undefined, {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit"
  });
}

function outcomeStyle(outcome: string): {
  bg: string;
  text: string;
  icon: React.ReactNode;
} {
  const o = outcome.toLowerCase();
  if (o === "ok" || o === "posted" || o === "approved" || o === "applied") {
    return {
      bg: "bg-credit/10 text-credit",
      text: "text-credit",
      icon: <CheckCircle2 size={12} />
    };
  }
  if (o === "rejected" || o === "blocked" || o === "error") {
    return {
      bg: "bg-debit/10 text-debit",
      text: "text-debit",
      icon: <XCircle size={12} />
    };
  }
  if (o === "queued" || o === "needs_review" || o === "pending") {
    return {
      bg: "bg-pending/10 text-pending",
      text: "text-pending",
      icon: <Clock size={12} />
    };
  }
  return {
    bg: "bg-white/[0.05] text-ink-secondary",
    text: "text-ink-secondary",
    icon: <Sparkles size={12} />
  };
}

function agentDisplayName(agentId: string): string {
  // strip vendor prefix
  let s = agentId.replace(/^(anthropic\/|openai\/|local\/)/, "");
  // friendlier presentation of known specialists
  const friendly: Record<string, string> = {
    "cpa-tax-resolver": "CPA Tax Resolver",
    "form-1120-preparer": "Form 1120 Preparer",
    "sc-state-specialist": "SC State Specialist",
    "1099-specialist": "1099-NEC Specialist",
    "personal-1040-specialist": "Personal 1040 Specialist",
    "books-lead": "Books Lead",
    "narrative-generator": "Narrative Generator"
  };
  if (friendly[s]) return friendly[s];
  return s;
}

